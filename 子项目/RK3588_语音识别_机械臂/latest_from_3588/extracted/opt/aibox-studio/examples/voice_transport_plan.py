"""综合实验的模拟规划练习；不发送任何机械臂动作。"""
from aibox import Voice

print("模拟规划练习：Voice.listen 返回模拟文字；真实联动请在功能演示中体验。")
print("口令格式：搬运红色积木到传送带（也支持绿色、蓝色、黄色）。")
text = Voice().listen(timeout=8).strip()
commands = {
    "搬运红色积木到传送带": "红色",
    "搬运绿色积木到传送带": "绿色",
    "搬运蓝色积木到传送带": "蓝色",
    "搬运黄色积木到传送带": "黄色",
}
color = commands.get(text)
if color is None:
    print("口令未匹配：请使用单一颜色、动作和目的地明确的完整口令。")
else:
    print("目标颜色：", color)
    print("1. 在功能演示打开语音搬运综合实验，检查设备与工作区域。")
    print("2. 初始化摄像头观察位置和机械臂直立姿态。")
    print("3. 开始监听并说出完整口令：", text)
    print("4. 视觉连续确认目标颜色；未确认或设备异常时不搬运。")
    print("5. 执行通用固定搬运动作组；颜色用于确认目标，不用于坐标抓取。")
    print("6. legacy_timed 模式等待驱动空闲后再等1秒，随后恢复直立。")
    print("本练习仅打印计划，未连接摄像头或麦克风，未发送机械臂动作。")
    print("软件时序，未验证物理到位；不代表目标已成功搬运。")
